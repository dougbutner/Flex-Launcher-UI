import { createConnection } from "mysql2/promise";
import fs from "node:fs";
import path from "node:path";

const host = process.env.MYSQL_HOST || "";
const user = process.env.MYSQL_USER || "";
const password = process.env.MYSQL_PASSWORD ?? "";
const database = process.env.MYSQL_DATABASE || "";
const port = Number(process.env.MYSQL_PORT || 3306) || 3306;
if (!host || !user || !database) {
  console.error("Set MYSQL_HOST, MYSQL_USER, MYSQL_PASSWORD, and MYSQL_DATABASE.");
  process.exit(1);
}

function sqlString(value) {
  if (value == null) return "NULL";
  return `'${String(value).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;
}

function insert(table, columns, rows) {
  if (!rows.length) return "";
  const lines = rows.map((row) => `(${columns.map((col) => sqlString(row[col])).join(", ")})`);
  const updates = columns
    .filter((col) => col !== columns[0])
    .map((col) => `${col} = VALUES(${col})`)
    .join(", ");
  return `INSERT INTO ${table} (${columns.join(", ")})\nVALUES\n${lines.join(",\n")}\nON DUPLICATE KEY UPDATE ${updates};\n`;
}

const conn = await createConnection({ host, user, password, database, port, dateStrings: true });
const [settings] = await conn.query("SELECT id, live, updated_at, updated_by FROM site_settings");
const [tokens] = await conn.query("SELECT contract, symbol, issuer, body, updated_at FROM manager_tokens ORDER BY contract, symbol");
const [posts] = await conn.query(
  "SELECT id, contract, symbol, author, parent_id, body, created_at, author_score, giphy_url FROM posts ORDER BY id"
);
const [tips] = await conn.query("SELECT id, post_id, from_account, amount, memo, created_at FROM tips ORDER BY id");
const [ups] = await conn.query(
  "SELECT id, post_id, from_account, to_account, amount_raw, quantity, txid, created_at FROM ups ORDER BY id"
);
const [txs] = await conn.query(
  "SELECT tx_id, actor, contract, action_name, symbol, actions_json, created_at FROM chain_txs ORDER BY created_at"
);
await conn.end();

const parts = [
  "-- Flex Launcher data.",
  "-- Generated by npm run db:export. Import after sql/schema.sql.",
  "-- Re-import updates rows. cache_entries and captcha are omitted (they expire).",
  "",
  insert(
    "site_settings",
    ["id", "live", "updated_at", "updated_by"],
    settings.length ? settings : [{ id: 1, live: 0, updated_at: 0, updated_by: "" }]
  ),
  insert("manager_tokens", ["contract", "symbol", "issuer", "body", "updated_at"], tokens),
  insert("posts", ["id", "contract", "symbol", "author", "parent_id", "body", "created_at", "author_score", "giphy_url"], posts),
  insert("tips", ["id", "post_id", "from_account", "amount", "memo", "created_at"], tips),
  insert("ups", ["id", "post_id", "from_account", "to_account", "amount_raw", "quantity", "txid", "created_at"], ups),
  insert("chain_txs", ["tx_id", "actor", "contract", "action_name", "symbol", "actions_json", "created_at"], txs),
].filter((part) => part !== "");

const file = path.resolve("sql/data.sql");
fs.writeFileSync(file, `${parts.join("\n")}\n`);
console.log(`Wrote ${file}`);
